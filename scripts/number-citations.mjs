// scripts/number-citations.mjs
//
// Every recording the draft cites, numbered once, in the order it first
// appears. A citation then reads `12|3:40`, so five timestamps in one
// paragraph stop looking alike when they come from five different days.
//
// The numbering is derived, never hand-kept: run this after editing the
// draft and the index and the bibliography both follow.
//
//     node scripts/number-citations.mjs
import { readFileSync, writeFileSync } from "node:fs";

const SRC = "components/testimony/TestimonyDraft.tsx";
const OUT = "data/testimonyCitations.ts";

const src = readFileSync(SRC, "utf8");

// Order of first appearance in the document, which is the order a reader
// meets them. Both spellings the body uses: a literal ULID and a constant.
const consts = Object.fromEntries(
    [...src.matchAll(/^const ([A-Z0-9_]+) = "([0-9A-HJKMNP-TV-Z]{26})";/gm)].map((m) => [m[1], m[2]]),
);

const order = [];
const seen = new Set();
for (const m of src.matchAll(/<Moment\s+ulid=(?:"([0-9A-HJKMNP-TV-Z]{26})"|\{([A-Z0-9_]+)\})/g)) {
    const ulid = m[1] ?? consts[m[2]];
    if (!ulid || seen.has(ulid)) continue;
    seen.add(ulid);
    order.push(ulid);
}

const body = order.map((u, i) => `    "${u}": ${i + 1},`).join("\n");
writeFileSync(
    OUT,
    `// data/testimonyCitations.ts — GENERATED by scripts/number-citations.mjs. Do not edit.
//
// Recording number to ULID, in the order the draft first cites each one. The
// draft renders a citation as <number>|<timestamp> and lists the whole set as
// a bibliography at the foot of the document.

export const DRAFT_CITATION_ORDER: string[] = [
${order.map((u) => `    "${u}",`).join("\n")}
];

export const DRAFT_CITATION_INDEX: Record<string, number> = {
${body}
};
`,
);

console.log(`${order.length} recordings numbered -> ${OUT}`);
